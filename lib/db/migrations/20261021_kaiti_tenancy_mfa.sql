-- KaitiOS Batch 3: multi-campaign tenancy + two-factor sign-in.
-- The API server applies this idempotently at boot (ensureTenancyAndMfaTables).

CREATE TABLE IF NOT EXISTS public.kaiti_organisations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.kaiti_campaigns (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organisation_id bigint NOT NULL REFERENCES public.kaiti_organisations(id),
  name text NOT NULL,
  seat text,
  area text,
  election_date date,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','paused','archived')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.kaiti_campaign_members (
  campaign_id bigint NOT NULL REFERENCES public.kaiti_campaigns(id) ON DELETE CASCADE,
  user_id integer NOT NULL,
  added_by text,
  added_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (campaign_id, user_id)
);
CREATE INDEX IF NOT EXISTS kaiti_campaign_members_user_idx ON public.kaiti_campaign_members(user_id);

