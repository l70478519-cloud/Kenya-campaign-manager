SELECT setval(pg_get_serial_sequence('public.kaiti_campaigns','id'), GREATEST((SELECT max(id) FROM public.kaiti_campaigns), 1));

-- Scope Batch 2 records by campaign.
ALTER TABLE public.kaiti_records ADD COLUMN IF NOT EXISTS owner_campaign_id bigint NOT NULL DEFAULT 1;
CREATE INDEX IF NOT EXISTS kaiti_records_campaign_module_idx ON public.kaiti_records(owner_campaign_id, module) WHERE deleted_at IS NULL;
ALTER TABLE public.kaiti_export_log ADD COLUMN IF NOT EXISTS campaign_id bigint;

CREATE TABLE IF NOT EXISTS public.kaiti_user_mfa (
  user_id integer PRIMARY KEY,
  secret_enc text,
  pending_secret_enc text,
  enabled boolean NOT NULL DEFAULT false,
  recovery_hashes jsonb NOT NULL DEFAULT '[]'::jsonb,
  last_step bigint,
  enabled_at timestamptz,
  last_used_at timestamptz
);

REVOKE ALL ON public.kaiti_organisations, public.kaiti_campaigns, public.kaiti_campaign_members, public.kaiti_user_mfa FROM anon, authenticated;
