#!/usr/bin/env node
/**
 * Builds artifacts/api-server/src/data/kenya-polling-centres.ts from the IEBC
 * polling-station register compiled at github.com/stevehoober254/kenya-county-data
 * (MIT). The source is pinned to one commit and checked by SHA-256, so the
 * output is reproducible.
 *
 * Every centre is placed under the app's canonical county → constituency → ward
 * tree (kenya-electoral-units.ts). The build fails, writing nothing, if any
 * centre cannot be placed or any of the 1,450 wards ends up with no centre.
 *
 * Usage (Node 22.18+ or 24, run from the repository root):
 *   node scripts/geo/build-polling-centres.mjs            # download pinned source
 *   node scripts/geo/build-polling-centres.mjs --source county_data.json
 *   node scripts/geo/build-polling-centres.mjs --check    # verify the committed file is current
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { KENYA_COUNTIES, findCounty, findConstituency, nameKey } from "../../artifacts/api-server/src/data/kenya-electoral-units.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(ROOT, "artifacts/api-server/src/data/kenya-polling-centres.ts");

export const SOURCE = {
  repository: "https://github.com/stevehoober254/kenya-county-data",
  commit: "183a54d19befae26a027291f8e2438d1c28e2ed7",
  file: "county_data.json",
  sha256: "a651ae320087d3bfa2f7c5c9b362ecd9c28105a9033d8252f48bf7e2319a7ad9",
  license: "MIT",
};
const SOURCE_URL = `https://raw.githubusercontent.com/stevehoober254/kenya-county-data/${SOURCE.commit}/${SOURCE.file}`;

/**
 * Register spellings for wards whose canonical name in this app deliberately
 * differs: Makueni keeps its CIDP 2023-2027 spellings, and the register has a
 * few typos. Keyed by county / constituency / register name.
 */
const SOURCE_WARD_ALIASES = {
  "Makueni/Makueni/Muvau/kikuumini": "Muvau/Kikumini",
  "Makueni/Mbooni/Kiteta/kisau": "Kisau/Kiteta",
  "Makueni/Mbooni/Waia-kako": "Kako/Waia",
  "Migori/Kuria West/Bukira Centrl/ikerege": "Bukira Central/Ikerege",
  "Homa Bay/Suba South/Ruma-kaksingri": "Ruma Kaksingri East",
  "Bungoma/Kanduyi/West Sangalo": "West Sang'alo",
};

const tidy = (s) => String(s ?? "").replace(/\s+/g, " ").trim();

function build(source) {
  if (!Array.isArray(source)) throw new Error("Source is not a county array");
  const out = {};
  for (const c of KENYA_COUNTIES) {
    out[c.name] = {};
    for (const k of c.constituencies) {
      out[c.name][k.name] = {};
      for (const w of k.wards) out[c.name][k.name][w] = [];
    }
  }
  const errors = [];
  let read = 0, duplicates = 0;
  for (const sc of source) {
    const county = findCounty(tidy(sc.name));
    if (!county) { errors.push(`County not in directory: ${sc.name}`); continue; }
    for (const sk of sc.constituencies ?? []) {
      const constituency = findConstituency(county, tidy(sk.name));
      if (!constituency) { errors.push(`Constituency not in ${county.name}: ${sk.name}`); continue; }
      for (const sw of sk.wards ?? []) {
        const raw = tidy(sw.name);
        const aliased = SOURCE_WARD_ALIASES[`${county.name}/${constituency.name}/${raw}`] ?? raw;
        const ward = constituency.wards.find((w) => nameKey(w) === nameKey(aliased));
        if (!ward) { errors.push(`Ward not in ${county.name}/${constituency.name}: ${raw}`); continue; }
        const list = out[county.name][constituency.name][ward];
        const seen = new Set(list.map(nameKey));
        for (const p of sw.pollingStations ?? []) {
          read++;
          const name = tidy(p?.name);
          if (!name) { errors.push(`Empty centre name in ${county.name}/${constituency.name}/${ward}`); continue; }
          if (seen.has(nameKey(name))) { duplicates++; continue; }
          seen.add(nameKey(name));
          list.push(name);
        }
      }
    }
  }
  for (const [county, ks] of Object.entries(out))
    for (const [k, ws] of Object.entries(ks))
      for (const [w, list] of Object.entries(ws)) if (!list.length) errors.push(`No centres for ${county}/${k}/${w}`);
  if (errors.length) throw new Error(`${errors.length} problem(s):\n  ${errors.slice(0, 40).join("\n  ")}`);
  const total = Object.values(out).flatMap(Object.values).flatMap(Object.values).reduce((n, l) => n + l.length, 0);
  return { data: out, stats: { read, duplicates, total } };
}

function render({ data, stats }) {
  return `/**
 * GENERATED by scripts/geo/build-polling-centres.mjs — do not edit by hand.
 *
 * Polling centres (polling-station locations) for every one of Kenya's 1,450
 * county assembly wards, arranged under the canonical county → constituency →
 * ward names in kenya-electoral-units.ts.
 *
 * Source: IEBC polling-station register as compiled at
 * ${SOURCE.repository} (${SOURCE.license}), commit ${SOURCE.commit.slice(0, 7)},
 * file ${SOURCE.file} (sha256 ${SOURCE.sha256.slice(0, 12)}…).
 *
 * The source gives centre names only. It has no IEBC station codes, registered
 * voters or stream counts, so none are included here; import the official IEBC
 * "Registered Voters per Polling Station" list for those. ${stats.read} source
 * entries, ${stats.duplicates} exact duplicates within a ward removed,
 * ${stats.total} centres kept.
 */
export const POLLING_CENTRE_SOURCE = ${JSON.stringify({ ...SOURCE, centres: stats.total })} as const;

/** county → constituency → ward → centre names. */
export const POLLING_CENTRES: Record<string, Record<string, Record<string, string[]>>> = ${JSON.stringify(data)};
`;
}

async function main() {
  const args = process.argv.slice(2);
  const sourceArg = args.includes("--source") ? args[args.indexOf("--source") + 1] : null;
  const text = sourceArg ? await readFile(sourceArg, "utf8") : await (await fetch(SOURCE_URL)).text();
  const digest = createHash("sha256").update(text).digest("hex");
  if (digest !== SOURCE.sha256) throw new Error(`Source checksum ${digest} does not match the pinned ${SOURCE.sha256}`);
  const result = build(JSON.parse(text));
  const rendered = render(result);
  if (args.includes("--check")) {
    const current = await readFile(OUT, "utf8").catch(() => "");
    if (current !== rendered) { console.error("kenya-polling-centres.ts is out of date. Run the build."); process.exit(1); }
    console.log("kenya-polling-centres.ts is current.");
    return;
  }
  await writeFile(OUT, rendered);
  console.log(`Wrote ${path.relative(ROOT, OUT)}: ${result.stats.total} centres in 1,450 wards (${result.stats.duplicates} duplicates removed).`);
}

main().catch((err) => { console.error(err.message ?? err); process.exit(1); });
